const assert=require('node:assert/strict')
const {readFile}=require('node:fs/promises')
const {ids}=require('./fixtures/history.cjs')
const card=(page,id)=>page.locator(`[data-history-video-id="${id}"]`)
async function guest({page}){
  await page.locator('a[href="#/history"]').first().click()
  await page.getByRole('heading',{name:'History',exact:true}).waitFor()
  assert.deepEqual(await page.locator('[data-history-video-id]').evaluateAll(nodes=>nodes.map(node=>node.dataset.historyVideoId)),['short000001','video000001'])
  await card(page,'short000001').locator('.wt-history-thumbnail').hover()
  await card(page,'short000001').getByRole('button',{name:/^Remove /}).click()
  await card(page,'short000001').waitFor({state:'detached'})
  assert.deepEqual((await page.evaluate(()=>window.api.getHistory())).map(item=>item.videoId),['video000001'])
  const state=await page.evaluate(()=>window.api.getSessionState())
  const db=JSON.parse(await readFile(state.dataPath,'utf8'))
  assert.equal(db.histories[state.activeProfileId].some(item=>item.videoId==='short000001'),false)
  assert.equal(Object.values(db.histories).some(items=>items.some(item=>item.videoId===ids.short)),true,'other account history is retained')
  await page.getByRole('link',{name:'Return home',exact:true}).click()
  await page.locator('a[href="#/history"]').first().click()
  await page.getByRole('heading',{name:'History',exact:true}).waitFor()
  await page.locator('a[href="#/account"]').first().click()
  console.log('PASS: guest Shorts use normal history order and individual removal persists without touching another account')
}
async function account({app,page,profile}){
  await page.locator('a[href="#/history"]').first().click()
  await page.getByRole('heading',{name:'History',exact:true}).waitFor()
  await card(page,ids.short).waitFor()
  assert.deepEqual(await page.getByRole('region',{name:'Shorts',exact:true}).locator('[data-history-video-id]').evaluateAll(nodes=>nodes.map(node=>node.dataset.historyVideoId)),[ids.short,ids.reel])
  assert.deepEqual(await page.locator('[data-history-videos] [data-history-video-id]').evaluateAll(nodes=>nodes.map(node=>node.dataset.historyVideoId)),[ids.regular,ids.lockup])
  const historyCarousel=page.getByRole('region',{name:'Shorts',exact:true}).locator('[data-shorts-carousel="history"]')
  assert.equal(await page.getByRole('button',{name:'Next Shorts',exact:true}).count(),0,
    'short rows without overflow must not show unnecessary arrows')
  await historyCarousel.evaluate(node=>{node.style.width='210px'})
  const historyNext=historyCarousel.getByRole('button',{name:'Next Shorts',exact:true})
  await historyNext.waitFor()
  const [historyBox,historyArrow]=await Promise.all([historyCarousel.boundingBox(),historyNext.boundingBox()])
  assert.ok(Math.abs(historyBox.x+historyBox.width-historyArrow.x-historyArrow.width)<3,
    'History next arrow must sit at the far right edge')
  await historyNext.click()
  await page.waitForFunction(() => {
    const node=document.querySelector('[data-history-shorts-strip]')
    return node && node.scrollLeft>20
  })
  const historyPrevious=historyCarousel.getByRole('button',{name:'Previous Shorts',exact:true})
  await historyPrevious.waitFor()
  await historyPrevious.click()
  await page.waitForFunction(() => {
    const node=document.querySelector('[data-history-shorts-strip]')
    return node && node.scrollLeft<2
  })
  assert.equal(await historyPrevious.count(),0)
  console.log('PASS: Shorts History shares edge-mounted arrows, hides them without overflow, and pages both ways')
  await page.getByRole('button',{name:'Hide Shorts',exact:true}).click()
  await page.getByRole('button',{name:'Show Shorts',exact:true}).waitFor()
  assert.equal(await page.getByRole('region',{name:'Shorts',exact:true}).locator('[data-history-video-id]').count(),0)
  assert.equal((await page.evaluate(()=>window.api.getAppPreferences())).showShortsHistory,false)
  await page.locator('a[href="#/subscriptions"]').first().click()
  await page.getByRole('button',{name:'Expand channels',exact:true}).waitFor()
  await page.locator('[data-subscriptions-layout="strip"]').waitFor()
  await page.getByRole('button',{name:'Expand channels',exact:true}).click()
  await page.locator('[data-subscriptions-layout="expanded"]').waitFor()
  assert.equal((await page.evaluate(()=>window.api.getAppPreferences())).subscriptionsExpanded,true)
  await page.locator('a[href="#/history"]').first().click()
  await page.getByRole('button',{name:'Show Shorts',exact:true}).waitFor()
  await page.getByRole('button',{name:'Show Shorts',exact:true}).click()
  await page.getByRole('button',{name:'Hide Shorts',exact:true}).waitFor()
  await card(page,ids.short).waitFor()
  assert.equal((await page.evaluate(()=>window.api.getAppPreferences())).showShortsHistory,true)
  await page.locator('a[href="#/subscriptions"]').first().click()
  await page.getByRole('button',{name:'Collapse channels',exact:true}).waitFor()
  await page.getByRole('button',{name:'Collapse channels',exact:true}).click()
  await page.getByRole('button',{name:'Expand channels',exact:true}).waitFor()
  assert.equal((await page.evaluate(()=>window.api.getAppPreferences())).subscriptionsExpanded,false)
  await page.locator('a[href="#/history"]').first().click()
  await card(page,ids.short).waitFor()
  const history=await page.evaluate(()=>window.api.getYoutubeHistory())
  assert.equal(JSON.stringify(history).includes('synthetic-history-remove'),false,'feedback tokens remain in main')
  assert.equal(history.videos.every(video=>video.canRemove),true)
  await card(page,ids.short).locator('.wt-history-thumbnail').hover()
  await card(page,ids.short).getByRole('button',{name:/^Remove /}).click()
  await card(page,ids.short).waitFor({state:'detached'})
  assert.equal(await app.evaluate(()=>globalThis.__historyFeedbackAuthenticated),true)
  assert.equal((await page.evaluate(()=>window.api.getHistory())).some(video=>video.videoId===ids.short),false)
  await page.getByRole('button',{name:'Load more',exact:true}).click()
  await card(page,ids.older).waitFor()
  assert.equal(await card(page,ids.short).count(),0,'stale continuation cannot resurrect a removed Short')
  await app.evaluate(()=>{globalThis.__historyFeedbackFails=true})
  await card(page,ids.lockup).locator('.wt-history-thumbnail').hover()
  await card(page,ids.lockup).getByRole('button',{name:/^Remove /}).click()
  await page.getByRole('alert').filter({hasText:'did not confirm removal'}).waitFor()
  assert.equal(await card(page,ids.lockup).count(),1)
  assert.equal((await page.evaluate(()=>window.api.getHistory())).some(video=>video.videoId===ids.lockup),true,'failed remote removal retains the local entry')
  await app.evaluate(()=>{globalThis.__historyFeedbackFails=false})
  await card(page,ids.lockup).locator('.wt-history-thumbnail').hover()
  await card(page,ids.lockup).getByRole('button',{name:/^Remove /}).click()
  await card(page,ids.lockup).waitFor({state:'detached'})
  const db=JSON.parse(await readFile(profile.dataPath,'utf8'))
  assert.equal(db.histories[profile.activeProfileId].some(video=>[ids.short,ids.lockup].includes(video.videoId)),false)
  assert.equal(db.histories['fixture-guest-profile'].some(video=>video.videoId==='video000001'),true)
  await page.locator('a[href="#/account"]').first().click()
  console.log('PASS: horizontal Shorts history and ordered normal videos, authenticated removal for Shorts/modern menus, pagination, honest failure/retry and local/account isolation')
}
module.exports={guest,account}
