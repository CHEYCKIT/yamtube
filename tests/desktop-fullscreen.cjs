const assert=require('node:assert/strict')
module.exports=async({app,page})=>{
  const requested=await app.evaluate(()=>globalThis.__featurePlaybackRequests.length)
  await page.locator('.shaka-fullscreen-button:visible').first().click({force:true})
  await page.waitForFunction(()=>document.fullscreenElement?.classList.contains('shaka-video-container'),{},{timeout:5000})
  let bounds=await page.locator('.shaka-video-container:fullscreen').boundingBox()
  let viewport=await page.evaluate(()=>({width:innerWidth,height:innerHeight}))
  assert.ok(Math.abs(bounds.width-viewport.width)<2 && Math.abs(bounds.height-viewport.height)<2)
  await page.keyboard.press('Escape')
  await page.waitForFunction(()=>!document.fullscreenElement)
  await page.keyboard.press('f')
  await page.waitForFunction(()=>!!document.fullscreenElement)
  await page.keyboard.press('f')
  await page.waitForFunction(()=>!document.fullscreenElement)
  await page.keyboard.press('t')
  await page.waitForFunction(()=>!!document.querySelector('.wt-theater'))
  await page.keyboard.press('f')
  await page.waitForFunction(()=>!!document.fullscreenElement)
  await page.keyboard.press('Escape')
  await page.waitForFunction(()=>!document.fullscreenElement)
  assert.equal(await page.locator('.wt-theater').count(),1,'leaving fullscreen restores theater mode')
  await page.keyboard.press('t')
  await page.waitForFunction(()=>!document.querySelector('.wt-theater'))
  await page.locator('.shaka-fullscreen-button:visible').first().click({force:true})
  await page.waitForFunction(()=>!!document.fullscreenElement)
  await page.locator('.shaka-pip-button:visible').first().click({force:true})
  await page.getByRole('heading',{name:'Home',exact:true}).waitFor()
  await page.waitForFunction(()=>!!document.pictureInPictureElement && !document.fullscreenElement)
  await page.getByRole('button',{name:'Return to video',exact:true}).click()
  await page.waitForFunction(()=>!document.pictureInPictureElement && !!document.querySelector('.wt-watch-player-slot video'))
  assert.equal(await page.evaluate(()=>document.querySelector('.wt-watch-player-slot video')===window.__pipVideo),true)
  assert.equal(await app.evaluate(()=>globalThis.__featurePlaybackRequests.length),requested)
  assert.equal(await page.evaluate(()=>Notification.requestPermission()),'denied')
  console.log('PASS: fullscreen button/F/Escape, theater restoration and fullscreen-to-PiP retain media; unrelated permissions stay denied')
}
