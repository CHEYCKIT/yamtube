const assert=require('node:assert/strict')

module.exports=async({app,page})=>{
  const originalSize=await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].getContentSize())
  const resize=async(width,height,zoom=1)=>{
    await app.evaluate(({BrowserWindow},{width,height,zoom})=>{
      const window=BrowserWindow.getAllWindows()[0]
      window.setContentSize(width,height)
      window.webContents.setZoomFactor(zoom)
    },{width,height,zoom})
    await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))))
    await page.waitForFunction(()=>{
      const nav=document.querySelector('.wt-sidebar')
      const expected=innerWidth<=680 ? document.documentElement.clientWidth : 112
      return Math.abs(nav.getBoundingClientRect().width-expected)<1
    })
  }
  for(const [width,height,zoom] of [[1366,768,1],[1024,600,1],[1366,768,1.5],[640,600,1]]) {
    await resize(width,height,zoom)
    const clipped=await page.locator('.wt-sidebar').evaluate(nav=>{
      const scroller=nav.firstElementChild
      const navBounds=nav.getBoundingClientRect()
      const right=navBounds.left+scroller.clientWidth
      return [...nav.querySelectorAll('.wt-nav-label')].flatMap(label=>{
        const range=document.createRange();range.selectNodeContents(label)
        const anchor=label.closest('a').getBoundingClientRect()
        const bad=[...range.getClientRects()].some(rect=>rect.left<anchor.left-1 || rect.right>Math.min(anchor.right,right)+1 || rect.top<anchor.top-1 || rect.bottom>anchor.bottom+1)
        return bad || label.scrollWidth>label.clientWidth+1 ? [{text:label.textContent,scrollWidth:label.scrollWidth,clientWidth:label.clientWidth,anchor:anchor.toJSON(),rects:[...range.getClientRects()].map(rect=>rect.toJSON()),right}] : []
      })
    })
    if(clipped.length) await page.screenshot({path:'.cache/loktube-sidebar-failure.png'})
    assert.deepEqual(clipped,[],`sidebar labels must fit at ${width}x${height}, zoom ${zoom}`)
  }
  console.log('PASS: all sidebar labels fit laptop, narrow-window and 150% zoom layouts, including a scrolling sidebar')
  await resize(1366,768)
  await page.locator('[data-video-id="jNQXAC9IVRw"]:visible a[href="#/watch/jNQXAC9IVRw"]').first().click()
  const slot=page.locator('.wt-watch-player-slot:visible')
  await slot.locator('video').waitFor()
  await page.waitForFunction(()=>{const video=document.querySelector('.wt-watch-player-slot video');return video?.readyState>=2})
  await page.evaluate(()=>{
    window.__theaterVideo=document.querySelector('.wt-watch-player-slot video')
    window.__theaterVideo.pause()
    window.__theaterVideo.currentTime=3
  })
  const requested=await app.evaluate(()=>globalThis.__featurePlaybackRequests.length)
  const normal=await slot.boundingBox()
  const button=page.locator('.shaka-theater-button:visible')
  await button.click({force:true})
  await page.waitForFunction(()=>document.querySelector('.wt-app-shell').classList.contains('wt-theater'))
  await page.mouse.move(500,350)
  await page.waitForFunction(()=>{
    const header=document.querySelector('.wt-topbar').getBoundingClientRect()
    const sidebar=document.querySelector('.wt-sidebar').getBoundingClientRect()
    return header.bottom<=1 && sidebar.right<=1
  })
  const expanded=await slot.boundingBox()
  const viewport=await page.evaluate(()=>({width:document.documentElement.clientWidth,height:innerHeight}))
  assert.ok(expanded.width>normal.width)
  assert.ok(Math.abs(expanded.x)<1 && Math.abs(expanded.y)<1)
  assert.ok(Math.abs(expanded.width-viewport.width)<2 && Math.abs(expanded.height-viewport.height)<2)
  assert.equal(await page.locator('.watch-sidebar-area:visible').evaluate(node=>node.getBoundingClientRect().top>=innerHeight),true)
  assert.equal(await button.getAttribute('aria-pressed'),'true')
  assert.equal(await page.evaluate(()=>document.querySelector('.wt-watch-player-slot video')===window.__theaterVideo && window.__theaterVideo.paused && Math.abs(window.__theaterVideo.currentTime-3)<0.1),true)
  assert.equal(await app.evaluate(()=>globalThis.__featurePlaybackRequests.length),requested)
  await page.screenshot({path:'.cache/loktube-theater.png'})

  await page.mouse.move(500,2)
  await page.waitForFunction(()=>Math.abs(document.querySelector('.wt-topbar').getBoundingClientRect().top)<1 && Math.abs(document.querySelector('.wt-tabbar').getBoundingClientRect().top-60)<1)
  const search=page.getByRole('textbox',{name:'Search',exact:true})
  await search.click()
  await search.fill('test theater typing')
  await page.keyboard.press('t')
  assert.equal(await page.locator('.wt-theater').count(),1,'typing t into search must not change theater mode')
  await page.mouse.move(500,350)
  assert.equal(await page.locator('.wt-topbar').evaluate(node=>Math.abs(node.getBoundingClientRect().top)<1),true,'search stays revealed while focused')
  await page.screenshot({path:'.cache/loktube-theater-header.png'})
  await search.fill('')
  await search.evaluate(node=>node.blur())
  await page.waitForFunction(()=>document.querySelector('.wt-topbar').getBoundingClientRect().bottom<=1)
  await page.mouse.move(2,200)
  await page.waitForFunction(()=>Math.abs(document.querySelector('.wt-sidebar').getBoundingClientRect().left)<1)
  assert.equal(await page.locator('.wt-sidebar').evaluate(node=>Math.abs(node.getBoundingClientRect().top)<1 && Math.abs(node.getBoundingClientRect().height-innerHeight)<2),true,'the sidebar must fill the left edge without reserving hidden header space')
  assert.equal(await page.locator('.wt-sidebar a').first().evaluate(node=>node.getBoundingClientRect().top<30),true,'Home starts at the top when only the sidebar is revealed')
  await page.screenshot({path:'.cache/loktube-theater-sidebar.png'})
  await page.mouse.move(500,350)
  await page.waitForFunction(()=>document.querySelector('.wt-sidebar').getBoundingClientRect().right<=1)
  await page.locator('.wt-sidebar a').first().focus()
  await page.waitForFunction(()=>Math.abs(document.querySelector('.wt-sidebar').getBoundingClientRect().left)<1)
  await page.locator('.wt-sidebar a').first().evaluate(node=>node.blur())
  await page.getByRole('button',{name:'Show search and tabs',exact:true}).focus()
  await page.waitForFunction(()=>Math.abs(document.querySelector('.wt-topbar').getBoundingClientRect().top)<1)
  await page.getByRole('button',{name:'Show search and tabs',exact:true}).press('Enter')
  assert.equal(await search.evaluate(node=>document.activeElement===node),true)
  await page.getByRole('button',{name:'Close window',exact:true}).waitFor()
  await page.mouse.move(2,200)
  await page.waitForFunction(()=>Math.abs(document.querySelector('.wt-sidebar').getBoundingClientRect().left)<1)
  assert.equal(await page.locator('.wt-sidebar a').first().evaluate(node=>node.getBoundingClientRect().top<30),true,'the header and sidebar may overlap; neither reserves a gap for the other')
  await search.evaluate(node=>node.blur())
  await page.mouse.move(500,350)
  await page.keyboard.press('t')
  await page.waitForFunction(()=>!document.querySelector('.wt-app-shell').classList.contains('wt-theater'))
  assert.equal(await button.getAttribute('aria-pressed'),'false')
  assert.equal(await page.evaluate(()=>document.querySelector('.wt-watch-player-slot video')===window.__theaterVideo && Math.abs(window.__theaterVideo.currentTime-3)<0.1),true)
  await page.evaluate(()=>window.__theaterVideo.play())
  await page.waitForFunction(()=>window.__theaterVideo.currentTime>3.1)
  await page.evaluate(()=>window.__theaterVideo.pause())
  assert.equal(await app.evaluate(()=>globalThis.__featurePlaybackRequests.length),requested)
  console.log('PASS: theater button/T shortcut, full-window player, hover/focus navigation and uninterrupted video identity/position')

  await page.keyboard.press('t')
  await page.waitForFunction(()=>!!document.querySelector('.wt-theater'))
  await page.mouse.move(500,2)
  await page.waitForFunction(()=>Math.abs(document.querySelector('.wt-topbar').getBoundingClientRect().top)<1)
  await search.fill('theater test')
  await search.press('Enter')
  await page.getByRole('heading',{name:'Results for “theater test”'}).waitFor()
  assert.equal(await page.locator('.wt-theater').count(),0,'browsing pages retain their normal layout')
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].emit('app-command',{},'browser-backward'))
  await page.waitForFunction(()=>!!document.querySelector('.wt-theater'))
  await page.mouse.move(500,350)
  await search.evaluate(node=>node.blur())
  await page.keyboard.press('t')
  await page.waitForFunction(()=>!document.querySelector('.wt-theater'))
  await resize(...originalSize)
  console.log('PASS: theater preference applies to watch pages while search keeps its normal layout')
}
